import json
import os
import unittest


def evaluate_agent_output(agent_output_json, ground_truth_json, scenario_json=None):
    """Evaluates agent output predictions against ground truth datasets and scenario events.

    Args:
        agent_output_json (dict): The output dictionary generated by the agent.
        ground_truth_json (dict): The expected ground truth dictionary.
        scenario_json (dict, optional): The input scenario dictionary containing events.

    Returns:
        dict: Evaluation results containing pass/fail status and details of checks.
    """
    errors = []

    # 1. Required fields presence and non-emptiness check
    required_fields = ["summary", "root_cause", "evidence", "response_actions"]
    for field in required_fields:
        if field not in agent_output_json:
            errors.append(f"Missing required field: '{field}'")
        else:
            val = agent_output_json[field]
            if val is None or (isinstance(val, (str, list, dict)) and len(val) == 0):
                errors.append(f"Required field '{field}' is empty")

    # 2. Assessed severity evaluation
    expected_severity = ground_truth_json.get("assessed_severity")
    actual_severity = agent_output_json.get("assessed_severity")
    if actual_severity != expected_severity:
        errors.append(
            f"Severity mismatch: expected '{expected_severity}', got '{actual_severity}'"
        )

    # 3. Confidence score evaluation
    confidence = agent_output_json.get("confidence_score")
    if not isinstance(confidence, (int, float)) or isinstance(confidence, bool):
        errors.append(f"Invalid confidence_score type: {type(confidence).__name__}")
    else:
        if not (0.0 <= float(confidence) <= 1.0):
            errors.append(f"Confidence score out of range [0.0, 1.0]: {confidence}")
        if float(confidence) < 0.85:
            errors.append(f"Confidence score below minimum threshold 0.85: {confidence}")

    # 4. Evidence source_event_id validation against scenario events
    if scenario_json and "events" in scenario_json:
        valid_event_ids = {evt["event_id"] for evt in scenario_json.get("events", [])}
        evidence_list = agent_output_json.get("evidence", [])
        if isinstance(evidence_list, list):
            for idx, item in enumerate(evidence_list):
                if isinstance(item, dict):
                    source_id = item.get("source_event_id")
                    if source_id not in valid_event_ids:
                        errors.append(
                            f"Evidence item [{idx}] references invalid source_event_id: '{source_id}'"
                        )

    return {
        "passed": len(errors) == 0,
        "errors": errors,
    }


class TestAgentEval(unittest.TestCase):
    def setUp(self):
        self.base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        self.scenario_path = os.path.join(
            self.base_dir, "data", "scenarios", "primary_attack.json"
        )
        self.ground_truth_path = os.path.join(
            self.base_dir, "data", "ground_truth", "primary_attack_expected.json"
        )

        with open(self.scenario_path, "r", encoding="utf-8") as f:
            self.scenario_data = json.load(f)

        with open(self.ground_truth_path, "r", encoding="utf-8") as f:
            self.ground_truth_data = json.load(f)

    def test_primary_attack_ground_truth_evaluation(self):
        # Evaluate ground truth against itself and scenario to ensure baseline passes
        result = evaluate_agent_output(
            self.ground_truth_data, self.ground_truth_data, self.scenario_data
        )
        self.assertTrue(
            result["passed"],
            f"Evaluation failed with errors: {result['errors']}",
        )

    def test_evaluation_severity_mismatch(self):
        modified_output = dict(self.ground_truth_data)
        modified_output["assessed_severity"] = "HIGH"
        result = evaluate_agent_output(
            modified_output, self.ground_truth_data, self.scenario_data
        )
        self.assertFalse(result["passed"])
        self.assertTrue(
            any("Severity mismatch" in err for err in result["errors"])
        )

    def test_evaluation_confidence_score_threshold(self):
        modified_output = dict(self.ground_truth_data)
        modified_output["confidence_score"] = 0.80
        result = evaluate_agent_output(
            modified_output, self.ground_truth_data, self.scenario_data
        )
        self.assertFalse(result["passed"])
        self.assertTrue(
            any("below minimum threshold" in err for err in result["errors"])
        )

    def test_evaluation_invalid_event_id_reference(self):
        modified_output = dict(self.ground_truth_data)
        modified_output["evidence"] = [
            {
                "description": "Invalid event test",
                "source_event_id": "EVT-INVALID-9999",
                "relevance": "Testing",
            }
        ]
        result = evaluate_agent_output(
            modified_output, self.ground_truth_data, self.scenario_data
        )
        self.assertFalse(result["passed"])
        self.assertTrue(
            any("invalid source_event_id" in err for err in result["errors"])
        )

    def test_evaluation_missing_required_fields(self):
        modified_output = dict(self.ground_truth_data)
        del modified_output["summary"]
        result = evaluate_agent_output(
            modified_output, self.ground_truth_data, self.scenario_data
        )
        self.assertFalse(result["passed"])
        self.assertTrue(
            any("Missing required field: 'summary'" in err for err in result["errors"])
        )


if __name__ == "__main__":
    unittest.main()
